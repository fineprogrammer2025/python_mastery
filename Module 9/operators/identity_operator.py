print("identity_oprator 'is'")
a = 2
b = 6
c = a
print(a is b)
print(a is c)
print("-------------------------")

print("identity_oprator 'is not'")
a = 2
b = 6
c = a
print(a is not b)
print(a is not c)
print("-------------------------")

print("membership_oprator 'in'")
numbers = [1,2,3,4]
print(2 in numbers)

colors = ["blue", "red", "yellow"]
print("green" in colors)

print("-------------------------")

print("membership_oprator 'not in'")
numbers = [1,2,3,4]
print(2 not in numbers)

colors = ["blue", "red", "yellow"]
print("green" not in colors)